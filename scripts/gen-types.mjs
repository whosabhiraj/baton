// npm run gen:types: protocol/schema/*.json -> web/src/protocol.gen.ts (committed; check fails on drift).
// Each schema becomes one namespace (named after the file) so $defs with the same name don't clash.
// Use: import type { ApiState } from './protocol.gen'; ApiState.RunSummary
import { compile } from 'json-schema-to-typescript';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './_lib.mjs';

const dir = join(root, 'protocol', 'schema');
// agent./hub./inbox. files are payload schemas: suffix them so inbox.message != inbox-message.
const ns = (file) => {
  const stem = file.replace(/\.json$/, '');
  const name = stem.split(/[._-]/).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
  return /^(agent|hub|inbox)\./.test(stem) ? `${name}Payload` : name;
};
let out = '// Generated by `npm run gen:types` from protocol/schema. Do not edit.\n/* eslint-disable */\n';
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const schema = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  delete schema.$id; // ids are not resolvable URLs; refs are all local (#/$defs/...)
  const ts = await compile(schema, 'Root', {
    bannerComment: '',
    additionalProperties: false,
    unknownAny: true,
    format: true,
    style: { singleQuote: true },
    cwd: dir,
  });
  out += `\nexport namespace ${ns(file)} {\n${ts.trim().replace(/^/gm, '  ')}\n}\n`;
}
writeFileSync(join(root, 'web', 'src', 'protocol.gen.ts'), out.replace(/[ \t]+$/gm, ''));
console.log('wrote web/src/protocol.gen.ts');
