// Package proto holds the BATON/1 wire types and validation. Validation is delegated to the
// embedded JSON Schema files (package protocol); payloads stay generic JSON so unknown types
// and fields are preserved.
package proto

import (
	"bytes"
	"encoding/json"
	"reflect"
	"sort"
	"strings"
	"sync"
)

// Version is the protocol version carried in every envelope as "v".
const Version = 1

// Source says where an event entered the hub.
type Source string

// Event sources.
const (
	SrcCLI     Source = "cli"
	SrcSpool   Source = "spool"
	SrcHub     Source = "hub"
	SrcAdapter Source = "adapter"
)

// RunStatus is the lifecycle status of a run.
type RunStatus string

// Run statuses (run-record.json enum).
const (
	StatusStarting    RunStatus = "starting"
	StatusRunning     RunStatus = "running"
	StatusWaiting     RunStatus = "waiting"
	StatusBlocked     RunStatus = "blocked"
	StatusPaused      RunStatus = "paused"
	StatusStalled     RunStatus = "stalled"
	StatusRateLimited RunStatus = "rate_limited"
	StatusDone        RunStatus = "done"
	StatusFailed      RunStatus = "failed"
	StatusKilled      RunStatus = "killed"
	StatusExited      RunStatus = "exited"
)

// PlanStep is one step of a plan.
type PlanStep struct {
	ID         string `json:"id"`
	Title      string `json:"title"`
	Acceptance string `json:"acceptance"`
}

// Envelope is a message as sent by an agent (envelope.incoming.json). Unknown top-level
// fields are kept in Extra and written back by MarshalJSON.
type Envelope struct {
	V       int                        `json:"v"`
	RunID   string                     `json:"run_id"`
	AgentID string                     `json:"agent_id"`
	Seq     *int64                     `json:"seq,omitempty"`
	TS      string                     `json:"ts,omitempty"`
	Type    string                     `json:"type"`
	Payload map[string]any             `json:"payload,omitempty"`
	MsgID   string                     `json:"msg_id,omitempty"`
	Extra   map[string]json.RawMessage `json:"-"`
}

// StoredEvent is a line of events.jsonl (envelope.stored.json).
type StoredEvent struct {
	V         int                        `json:"v"`
	RunID     string                     `json:"run_id"`
	AgentID   string                     `json:"agent_id"`
	Seq       int64                      `json:"seq"`
	TS        string                     `json:"ts"`
	Type      string                     `json:"type"`
	Payload   map[string]any             `json:"payload"`
	MsgID     string                     `json:"msg_id"`
	Src       Source                     `json:"src"`
	ClientSeq *int64                     `json:"client_seq,omitempty"`
	Extra     map[string]json.RawMessage `json:"-"`
}

// InboxMessage is a hub-to-agent inbox file body (inbox-message.json).
type InboxMessage struct {
	V       int            `json:"v"`
	N       int            `json:"n"`
	TS      string         `json:"ts"`
	Type    string         `json:"type"`
	Payload map[string]any `json:"payload"`
}

// RunRecord is the content of run.json (run-record.json). Unknown fields are kept in Extra.
type RunRecord struct {
	RunID        string                     `json:"run_id"`
	AgentID      string                     `json:"agent_id"`
	Callsign     string                     `json:"callsign,omitempty"`
	AccountID    string                     `json:"account_id,omitempty"`
	Role         string                     `json:"role,omitempty"`
	Kind         string                     `json:"kind,omitempty"`
	Model        string                     `json:"model,omitempty"`
	Status       RunStatus                  `json:"status"`
	CreatedAt    string                     `json:"created_at"`
	EndedAt      string                     `json:"ended_at,omitempty"`
	TokenSHA256  string                     `json:"token_sha256"`
	TokenRevoked bool                       `json:"token_revoked"`
	Plan         []PlanStep                 `json:"plan"`
	Extra        map[string]json.RawMessage `json:"-"`
}

// Lists of known message types.
var (
	// AgentTypes are the types agents may send (payload schema agent.<type>).
	AgentTypes = []string{"hello", "plan", "step_start", "step_done", "step_blocked", "progress",
		"artifact", "question", "heartbeat", "done", "error"}
	// HubOnlyTypes are generated by the hub; agents sending them get HUB_ONLY_TYPE (A6).
	HubOnlyTypes = []string{"activity", "exit", "rate_limited", "killed", "paused", "resumed",
		"stalled", "to_agent"}
	// InboxTypes are the hub-to-agent inbox message types (payload schema inbox.<type>).
	InboxTypes = []string{"message", "answer", "plan_update", "pause", "resume", "stop"}
)

// IsHubOnly reports whether t is a hub-generated type that agents may not send.
func IsHubOnly(t string) bool {
	for _, h := range HubOnlyTypes {
		if h == t {
			return true
		}
	}
	return false
}

// MarshalLine encodes v as one compact JSON line (no HTML escaping) terminated by '\n'.
// It returns nil if v cannot be encoded.
func MarshalLine(v any) []byte {
	b, err := marshalNoEscape(v)
	if err != nil {
		return nil
	}
	return append(b, '\n')
}

// marshalNoEscape is json.Marshal without HTML escaping and without the trailing newline.
func marshalNoEscape(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}

var knownKeysCache sync.Map

// knownKeys returns the JSON field names declared on struct type t.
func knownKeys(t reflect.Type) map[string]bool {
	if m, ok := knownKeysCache.Load(t); ok {
		return m.(map[string]bool)
	}
	m := map[string]bool{}
	for i := 0; i < t.NumField(); i++ {
		name, _, _ := strings.Cut(t.Field(i).Tag.Get("json"), ",")
		if name != "" && name != "-" {
			m[name] = true
		}
	}
	knownKeysCache.Store(t, m)
	return m
}

// marshalWithExtra encodes the (method-less) alias value and appends the extra fields.
func marshalWithExtra(alias any, extra map[string]json.RawMessage) ([]byte, error) {
	b, err := marshalNoEscape(alias)
	if err != nil || len(extra) == 0 {
		return b, err
	}
	keys := make([]string, 0, len(extra))
	for k := range extra {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b = b[:len(b)-1] // drop '}'
	for _, k := range keys {
		kb, _ := marshalNoEscape(k)
		b = append(b, ',')
		b = append(b, kb...)
		b = append(b, ':')
		b = append(b, extra[k]...)
	}
	return append(b, '}'), nil
}

// unmarshalWithExtra decodes data into alias (numbers as json.Number inside maps) and returns
// the top-level fields that alias does not declare.
func unmarshalWithExtra(data []byte, alias any) (map[string]json.RawMessage, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	if err := dec.Decode(alias); err != nil {
		return nil, err
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(data, &all); err != nil {
		return nil, err
	}
	known := knownKeys(reflect.TypeOf(alias).Elem())
	var extra map[string]json.RawMessage
	for k, v := range all {
		if !known[k] {
			if extra == nil {
				extra = map[string]json.RawMessage{}
			}
			extra[k] = v
		}
	}
	return extra, nil
}

type (
	envelopeAlias  Envelope
	storedAlias    StoredEvent
	runRecordAlias RunRecord
)

// MarshalJSON encodes the envelope, appending Extra fields.
func (e Envelope) MarshalJSON() ([]byte, error) {
	return marshalWithExtra(envelopeAlias(e), e.Extra)
}

// UnmarshalJSON decodes the envelope, keeping unknown fields in Extra.
func (e *Envelope) UnmarshalJSON(b []byte) error {
	var a envelopeAlias
	extra, err := unmarshalWithExtra(b, &a)
	if err != nil {
		return err
	}
	*e = Envelope(a)
	e.Extra = extra
	return nil
}

// MarshalJSON encodes the stored event (payload is never null), appending Extra fields.
func (e StoredEvent) MarshalJSON() ([]byte, error) {
	if e.Payload == nil {
		e.Payload = map[string]any{}
	}
	return marshalWithExtra(storedAlias(e), e.Extra)
}

// UnmarshalJSON decodes the stored event, keeping unknown fields in Extra.
func (e *StoredEvent) UnmarshalJSON(b []byte) error {
	var a storedAlias
	extra, err := unmarshalWithExtra(b, &a)
	if err != nil {
		return err
	}
	*e = StoredEvent(a)
	e.Extra = extra
	return nil
}

// MarshalJSON encodes the run record (plan is never null), appending Extra fields.
func (r RunRecord) MarshalJSON() ([]byte, error) {
	if r.Plan == nil {
		r.Plan = []PlanStep{}
	}
	return marshalWithExtra(runRecordAlias(r), r.Extra)
}

// UnmarshalJSON decodes the run record, keeping unknown fields in Extra.
func (r *RunRecord) UnmarshalJSON(b []byte) error {
	var a runRecordAlias
	extra, err := unmarshalWithExtra(b, &a)
	if err != nil {
		return err
	}
	*r = RunRecord(a)
	r.Extra = extra
	return nil
}
