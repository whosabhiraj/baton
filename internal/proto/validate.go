package proto

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
	"sync"

	"github.com/santhosh-tekuri/jsonschema/v6"

	"github.com/whosabhiraj/baton/protocol"
)

var (
	schemaMu    sync.Mutex
	schemaCache = map[string]*jsonschema.Schema{}
)

// Schema returns the compiled schema protocol/schema/<name>.json (for example "agent.plan").
// Schemas are compiled lazily and cached.
func Schema(name string) (*jsonschema.Schema, error) {
	schemaMu.Lock()
	defer schemaMu.Unlock()
	if s, ok := schemaCache[name]; ok {
		return s, nil
	}
	raw, err := protocol.Schemas.ReadFile("schema/" + name + ".json")
	if err != nil {
		return nil, fmt.Errorf("schema %q: %w", name, err)
	}
	doc, err := jsonschema.UnmarshalJSON(bytes.NewReader(raw))
	if err != nil {
		return nil, fmt.Errorf("schema %q: %w", name, err)
	}
	c := jsonschema.NewCompiler()
	url := "baton:///" + name + ".json"
	if err := c.AddResource(url, doc); err != nil {
		return nil, fmt.Errorf("schema %q: %w", name, err)
	}
	s, err := c.Compile(url)
	if err != nil {
		return nil, fmt.Errorf("schema %q: %w", name, err)
	}
	schemaCache[name] = s
	return s, nil
}

// ValidateJSON validates a decoded JSON value against the named schema. It returns nil when
// valid, otherwise a short human-readable reason.
func ValidateJSON(name string, v any) error {
	s, err := Schema(name)
	if err != nil {
		return err
	}
	// Normalise through JSON so Go ints/floats/json.Number all look the same to the validator.
	b, err := marshalNoEscape(v)
	if err != nil {
		return err
	}
	inst, err := jsonschema.UnmarshalJSON(bytes.NewReader(b))
	if err != nil {
		return err
	}
	return describe(s.Validate(inst))
}

func describe(err error) error {
	if err == nil {
		return nil
	}
	ve, ok := err.(*jsonschema.ValidationError)
	if !ok {
		return err
	}
	var parts []string
	for _, u := range ve.BasicOutput().Errors {
		if u.Error == nil {
			continue
		}
		loc := u.InstanceLocation
		if loc == "" {
			loc = "/"
		}
		parts = append(parts, loc+": "+u.Error.String())
		if len(parts) == 3 {
			break
		}
	}
	if len(parts) == 0 {
		return fmt.Errorf("schema validation failed")
	}
	return fmt.Errorf("%s", strings.Join(parts, "; "))
}

// ParseIncoming parses and validates an incoming envelope (envelope.incoming schema). Numbers
// in the payload stay exact (json.Number); a missing payload becomes {}. Errors are
// INVALID_ENVELOPE.
func ParseIncoming(b []byte) (Envelope, *Error) {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	var raw any
	if err := dec.Decode(&raw); err != nil {
		return Envelope{}, NewError(CodeInvalidEnvelope, "not valid JSON: "+err.Error())
	}
	if dec.More() {
		return Envelope{}, NewError(CodeInvalidEnvelope, "trailing data after JSON value")
	}
	if _, ok := raw.(map[string]any); !ok {
		return Envelope{}, NewError(CodeInvalidEnvelope, "envelope must be a JSON object")
	}
	if err := ValidateJSON("envelope.incoming", raw); err != nil {
		return Envelope{}, NewError(CodeInvalidEnvelope, err.Error())
	}
	var env Envelope
	if err := json.Unmarshal(b, &env); err != nil {
		return Envelope{}, NewError(CodeInvalidEnvelope, err.Error())
	}
	if env.Payload == nil {
		env.Payload = map[string]any{}
	}
	return env, nil
}

func validatePayload(schema string, p map[string]any) (map[string]any, *Error) {
	if p == nil {
		p = map[string]any{}
	}
	if err := ValidateJSON(schema, p); err != nil {
		return nil, NewError(CodeInvalidPayload, err.Error())
	}
	return p, nil
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

// ValidateAgentPayload checks the payload of an agent-sent message. Hub-only types yield
// HUB_ONLY_TYPE; known types are validated against agent.<type>; other types pass (A6).
// A nil payload is treated as {}.
func ValidateAgentPayload(typ string, p map[string]any) (map[string]any, *Error) {
	if IsHubOnly(typ) {
		return nil, NewError(CodeHubOnlyType, fmt.Sprintf("type %q can only be generated by the hub", typ))
	}
	if !contains(AgentTypes, typ) {
		if p == nil {
			p = map[string]any{}
		}
		return p, nil
	}
	return validatePayload("agent."+typ, p)
}

// ValidateInboxPayload checks a hub-to-agent message payload against inbox.<type>. Unknown
// types yield UNKNOWN_INBOX_TYPE.
func ValidateInboxPayload(typ string, p map[string]any) (map[string]any, *Error) {
	if !contains(InboxTypes, typ) {
		return nil, NewError(CodeUnknownInboxType, fmt.Sprintf("unknown inbox type %q", typ))
	}
	return validatePayload("inbox."+typ, p)
}

// ValidateHubPayload checks a hub-generated event payload against hub.<type>. Types not in
// HubOnlyTypes yield INVALID_PAYLOAD.
func ValidateHubPayload(typ string, p map[string]any) (map[string]any, *Error) {
	if !IsHubOnly(typ) {
		return nil, NewError(CodeInvalidPayload, fmt.Sprintf("%q is not a hub type", typ))
	}
	return validatePayload("hub."+typ, p)
}
